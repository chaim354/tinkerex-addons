test("PrusaSlicer: duration words, filament mm and g, layer height, the config block as settings, relative E extrudes", () => {
  const p = parseGcode(PRUSA);
  assert.equal(p.slicer, "PrusaSlicer");
  assert.equal(p.meta.slicerVersion, "2.8.0");
  assert.equal(p.meta.timeSeconds, 3723, "1h 2m 3s, the normal mode, not the silent one");
  assert.equal(p.meta.timeSource, "slicer");
  assert.equal(p.meta.filamentMm, 1234.5);
  assert.equal(p.meta.filamentG, 3.7);
  assert.equal(p.meta.layerHeight, 0.2);
  assert.equal(p.meta.firstLayerHeight, 0.2);
  assert.equal(p.meta.nozzleDiameter, 0.4);
  assert.equal(p.meta.nozzleTemp, 215);
  assert.equal(p.meta.bedTemp, 60);
  assert.equal(p.meta.layerCount, 2, "no slicer count: the parsed layers");
  const keys = p.meta.settings.map((s) => s.key);
  assert.ok(p.meta.settings.some((s) => s.key === "layer_height" && s.value === "0.2"));
  assert.ok(p.meta.settings.some((s) => s.key === "printer_notes" && s.value === ""), "an empty value survives");
  assert.ok(!keys.includes("prusaslicer_config"), "the block markers are not settings");
  assert.ok(!keys.some((k) => k.includes(" ")), "the prose header lines are not settings");
  assert.ok(!keys.includes("filament"), "'; filament used [mm] = ' is metadata, not a setting");
  assert.equal(p.mode, "fdm");
  assert.equal(p.layers.length, 2);
  const extruding = flat(p).filter((s) => s.extruding);
  assert.equal(extruding.length, 4, "each relative E0.5 move extrudes");
  assert.ok(flat(p).filter((s) => !s.extruding).length >= 4, "the Z and XY positioning moves are travels");
});

