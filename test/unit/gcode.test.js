test("Cura: slicer, time from ;TIME:, filament in metres, layer count, temperatures, bounds and mode", () => {
  const p = parseGcode(CURA);
  assert.equal(p.slicer, "Cura");
  assert.equal(p.meta.slicerVersion, "5.7.0");
  assert.equal(p.mode, "fdm");
  assert.equal(p.meta.timeSeconds, 3600);
  assert.equal(p.meta.timeSource, "slicer");
  assert.equal(p.estimatedFromMoves, false);
  assert.equal(p.meta.filamentMm, 1500);
  assert.equal(p.meta.filamentG, null);
  assert.equal(p.meta.layerCount, 2);
  assert.equal(p.meta.layerHeight, 0.2);
  assert.equal(p.layers.length, 2);
  assert.equal(p.meta.nozzleTemp, 210, "the first M104 with a temperature, not the M104 S0 at the end");
  assert.equal(p.meta.bedTemp, 60);
  assert.equal(p.bounds.extruding.max.x, 20, "the travel to 100,100 is not an extruding move");
  assert.equal(p.bounds.extruding.min.x, 10);
  assert.equal(p.bounds.extruding.max.z, 0.4);
  assert.equal(p.bounds.all.max.x, 100);
  assert.equal(p.bounds.all.min.x, 0);
  assert.deepEqual(p.feed, { min: 1200, max: 3000 });
  assert.equal(p.lineCount, 30);
  assert.deepEqual(p.warnings, []);
  assert.equal(p.meta.settings.length, 0, ";SETTING_3 is not a settings table");
});

test("Cura: layers start at the first extruding move after Z changed; travels stay with the current layer", () => {
  const p = parseGcode(CURA);
  assert.equal(p.layers[0].z, 0.2);
  assert.equal(p.layers[1].z, 0.4);
  const first = p.layers[0].segments;
  assert.equal(first[0].rapid, true, "the opening travel to Z0.2 is attached to the first layer");
  assert.equal(first.filter((s) => s.extruding).length, 2);
  const travel = first.find((s) => s.x1 === 100 && s.y1 === 100);
  assert.ok(travel && !travel.extruding, "the travel to 100,100 is in layer 0 as a non-extruding segment");
  const hop = first.find((s) => s.z0 === 0.2 && s.z1 === 0.4);
  assert.ok(hop && hop.rapid, "G0 Z0.4 is a travel in the layer it leaves, not the start of the next");
  assert.equal(p.layers[1].segments.filter((s) => s.extruding).length, 2);
  for (const s of flat(p)) {
    for (const k of ["x0", "y0", "z0", "x1", "y1", "z1"]) assert.equal(typeof s[k], "number", `${k} is a number`);
    assert.equal(typeof s.extruding, "boolean");
    assert.equal(typeof s.rapid, "boolean");
  }
});

