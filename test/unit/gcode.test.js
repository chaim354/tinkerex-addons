test("G91 makes moves relative: the second X5 ends at x 10", () => {
  const p = parseGcode(RELATIVE);
  const segs = flat(p);
  assert.equal(segs.length, 2);
  assert.equal(segs[0].x0, 0);
  assert.equal(segs[0].x1, 5);
  assert.equal(segs[1].x0, 5);
  assert.equal(segs[1].x1, 10);
  assert.ok(segs.every((s) => s.extruding), "under G91 with no M82/M83 the E words are relative too");
  assert.equal(p.mode, "fdm");
});

test("G92 sets the position without a segment: E0 resets extrusion, X0 shifts the frame", () => {
  const p = parseGcode(RESET);
  const segs = flat(p);
  assert.equal(segs.length, 3, "three G1 moves, no segment for either G92");
  assert.ok(segs.every((s) => s.extruding), "E climbs again from the reset 0");
  assert.equal(segs[1].x0, 10);
  assert.equal(segs[1].x1, 20);
  assert.equal(segs[2].x0, 0, "after G92 X0 the next move starts from 0");
  assert.equal(segs[2].x1, 5);
});

