test("summaryMarkdown names the file, the slicer, the time, the bounds and the settings", () => {
  const cura = summaryMarkdown(parseGcode(CURA), "benchy.gcode");
  assert.ok(cura.startsWith("# "), "a title");
  assert.ok(cura.includes("benchy.gcode"));
  assert.ok(cura.includes("Cura 5.7.0"));
  assert.ok(cura.includes("1h 00m"), "the slicer's hour, without seconds");
  assert.ok(!cura.includes("estimated from moves"));
  assert.ok(cura.includes("10 × 10 × 0.4 mm"), "W × D × H of the extruding bounds");
  assert.ok(cura.includes("1200–3000 mm/min"));
  assert.ok(cura.includes("210 °C"));

  const prusa = summaryMarkdown(parseGcode(PRUSA), "part.gcode");
  assert.ok(prusa.includes("| layer_height | 0.2 |"), "a settings table row");
  assert.ok(prusa.includes("1.23 m"), "filament in metres");
  assert.ok(prusa.includes("3.7 g"));

  const cnc = summaryMarkdown(parseGcode(CNC), "pocket.nc");
  assert.ok(cnc.includes("estimated from moves"));
  assert.ok(cnc.includes("CNC"));
  assert.ok(!cnc.includes("## Settings"), "no settings table when there are no settings");

  const pipes = parseGcode("; prusaslicer_config = begin\n; notes = a|b\n; prusaslicer_config = end\nG1 X1 F1\n");
  assert.ok(summaryMarkdown(pipes, "x.gcode").includes("a\\|b"), "a pipe in a value is escaped");
});
