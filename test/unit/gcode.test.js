// ---- CNC -----------------------------------------------------------------------------------------

test("CNC: no E means cnc, one layer per cutting Z (ascending), rapids attributed to the current Z", () => {
  const p = parseGcode(CNC);
  assert.equal(p.mode, "cnc");
  assert.equal(p.slicer, "unknown");
  assert.deepEqual(p.layers.map((l) => l.z), [-2, -1]);
  const deep = p.layers[0], shallow = p.layers[1];
  assert.ok(shallow.segments[0].rapid && shallow.segments[0].z1 === 5, "the opening G0 Z5 joins the first cutting layer");
  assert.ok(shallow.segments.some((s) => s.rapid && s.z0 === -1 && s.z1 === 5), "the retract after the arc stays at Z -1");
  assert.ok(deep.segments.every((s) => !s.rapid), "the plunge and the cut at -2");
  assert.equal(deep.segments[deep.segments.length - 1].x1, 0);
  assert.deepEqual(p.feed, { min: 300, max: 600 });
  assert.equal(p.bounds.extruding.min.z, -2, "for cnc the 'extruding' bounds are the cuts");
  assert.equal(p.bounds.extruding.max.z, 5, "the plunge from Z5 starts at Z5");
  assert.equal(p.bounds.all.max.z, 5);
});

test("CNC: a G2 arc is chords of at most 1 mm on the circle, clockwise, landing exactly on the end point", () => {
  const p = parseGcode(CNC);
  const segs = flat(p);
  const start = segs.findIndex((s) => s.x1 === 10 && s.y1 === 0 && s.z1 === -1);
  assert.ok(start >= 0, "the G1 X10 cut precedes the arc");
  const chords = [];
  for (let i = start + 1; i < segs.length && !segs[i].rapid; i++) chords.push(segs[i]);
  assert.ok(chords.length >= 2, `at least two chords, got ${chords.length}`);
  for (const c of chords) {
    assertNear(Math.hypot(c.x0 - 10, c.y0 - 10), 10, 1e-6, "chord start on the circle");
    assertNear(Math.hypot(c.x1 - 10, c.y1 - 10), 10, 1e-6, "chord end on the circle");
    assert.ok(Math.hypot(c.x1 - c.x0, c.y1 - c.y0) <= 1 + 1e-9, "a chord is at most 1 mm");
    assert.equal(c.extruding, false);
    assert.equal(c.rapid, false);
  }
  // From the bottom of the circle to its right-hand point, CLOCKWISE is the long way round through
  // the left: 270 degrees, 47.1 mm, 48 chords. A counter-clockwise reading would never pass x < 5.
  assert.ok(chords.some((c) => c.x1 < 5), "the arc runs through the left of the circle");
  assert.equal(chords.length, 48);
  const last = chords[chords.length - 1];
  assert.equal(last.x1, 20);
  assert.equal(last.y1, 10);
});

test("CNC: a G3 quarter arc stays in its quadrant, and an R arc takes the short way about the right centre", () => {
  const q = flat(parseGcode(QUARTER)).filter((s) => !s.rapid && !(s.z0 !== s.z1));
  assert.equal(q.length, 16, "15.7 mm of arc in 1 mm chords");
  for (const c of q) {
    assertNear(Math.hypot(c.x1 - 10, c.y1 - 10), 10, 1e-6, "on the circle");
    assert.ok(c.x1 >= 10 - 1e-9 && c.y1 <= 10 + 1e-9, "counter-clockwise from the bottom goes right, then up");
  }
  const r = flat(parseGcode(RADIUS)).filter((s) => !s.rapid && s.z0 === s.z1);
  assert.equal(r.length, 16);
  for (const c of r) {
    assertNear(Math.hypot(c.x1 - 10, c.y1 - 0), 10, 1e-6, "G2 R10 from 0,0 to 10,10 is centred on 10,0");
    assert.ok(c.x1 <= 10 + 1e-9 && c.y1 <= 10 + 1e-9, "the short arc stays in the upper-left quadrant of its centre");
  }
});

test("CNC: time is estimated from moves at each move's feed, 1500 mm/min before any F", () => {
  const p = parseGcode(CNC);
  assert.equal(p.estimatedFromMoves, true);
  assert.equal(p.meta.timeSource, "moves");
  assert.ok(p.meta.timeSeconds > 0);
  // 5 mm at 1500 + 6 mm at 300 + 10 mm at 600 + 47.12 mm of arc at 600 + 6 + 7 + 20 mm at 600
  const expected = 5 * 60 / 1500 + 6 * 60 / 300 + (10 + 1.5 * Math.PI * 10 + 6 + 7 + 20) * 60 / 600;
  assertNear(p.meta.timeSeconds, expected, 1e-6, "sum of length over feed");
});

